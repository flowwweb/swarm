    await page.waitForFunction(()=>!flowEditor.pending && !flowEditor.dirty);
    assert.equal(definitions.length,3);
    assert.equal(definitions[2].nodes.length,2);
    await page.getByLabel('Objective',{exact:true}).scrollIntoViewIfNeeded();
